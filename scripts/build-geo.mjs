// Builds src/geo.js from Natural Earth 1:50m GeoJSON (public domain).
// Usage: node scripts/build-geo.mjs <dir with ne_50m land/countries/lakes .geojson>
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = process.argv[2];
if (!dir) throw new Error('usage: build-geo.mjs <natural-earth-dir>');
const read = (f) => JSON.parse(readFileSync(join(dir, f), 'utf8'));

// A little wider than the map view so lines leave the frame instead of stopping short.
const BOX = { w: 23, e: 47, s: 33, n: 45 };
const inBox = ([x, y]) => x >= BOX.w && x <= BOX.e && y >= BOX.s && y <= BOX.n;

function rings(geom) {
  if (geom.type === 'Polygon') return geom.coordinates;
  if (geom.type === 'MultiPolygon') return geom.coordinates.flat();
  return [];
}

// Douglas-Peucker; tolerance in degrees.
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  // A closed ring starts and ends on the same point, which leaves no baseline to measure from.
  const [fx, fy] = pts[0], [lx, ly] = pts[pts.length - 1];
  if (fx === lx && fy === ly) {
    const mid = pts.length >> 1;
    return [...simplify(pts.slice(0, mid + 1), tol).slice(0, -1), ...simplify(pts.slice(mid), tol)];
  }
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

// Split a ring into runs that stay inside the box, keeping one point past each edge.
function clip(ring) {
  const runs = [];
  let cur = [];
  ring.forEach((p, i) => {
    const inside = inBox(p);
    if (inside) {
      if (!cur.length && i > 0) cur.push(ring[i - 1]);
      cur.push(p);
    } else if (cur.length) {
      cur.push(p);
      runs.push(cur);
      cur = [];
    }
  });
  if (cur.length) runs.push(cur);
  return runs.filter((r) => r.length > 1);
}

function lines(features, tol) {
  const out = [];
  for (const f of features) {
    for (const ring of rings(f.geometry)) {
      for (const run of clip(ring)) {
        const s = simplify(run, tol);
        if (s.length > 1) out.push(s.flatMap(([x, y]) => [+x.toFixed(2), +y.toFixed(2)]));
      }
    }
  }
  return out;
}

const countries = read('ne_50m_admin_0_countries.geojson').features;
const turkey = countries.filter((f) => f.properties.ADM0_A3 === 'TUR');
const borders = countries.filter((f) => f.properties.ADM0_A3 !== 'TUR');
const lakes = read('ne_50m_lakes.geojson').features;

const geo = {
  land: lines(read('ne_50m_land.geojson').features, 0.03),
  borders: lines(borders, 0.03),
  turkey: lines(turkey, 0.015),
  lakes: lines(lakes, 0.02),
};

const body = Object.entries(geo)
  .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`)
  .join('\n');
writeFileSync(
  new URL('../src/geo.js', import.meta.url),
  `// Generated by scripts/build-geo.mjs from Natural Earth 1:50m (public domain). Do not edit.\n// Each line is a flat [lon, lat, lon, lat, ...] array.\n${body}\n`,
);
console.log(Object.fromEntries(Object.entries(geo).map(([k, v]) => [k, v.length])));
